def _alter():
    """幂等新增列"""
    with engine.begin() as conn:
        checks = {
            "food_group": "ALTER TABLE ingredients ADD COLUMN food_group VARCHAR(50) NULL",
            "nutrition": "ALTER TABLE ingredients ADD COLUMN nutrition JSON NULL",
            "diet_tags": "ALTER TABLE ingredients ADD COLUMN diet_tags JSON NULL",
        }
        existing = {r[0] for r in conn.execute(text("SHOW COLUMNS FROM ingredients"))}
        for col, ddl in checks.items():
            if col not in existing:
                conn.execute(text(ddl))
                print("ALTER +", col)


def classify_and_score(name: str) -> tuple:
    """返回 (food_group, diet_tags, nutrition_dict)"""
    # 忌口标签
    tags = []
    for tag, kws in DIET_RULES:
        if any(k in name for k in kws) and tag not in tags:
            tags.append(tag)
    # 荤素
    if any(k in name for k in MEAT_KEYWORDS):
        tags.append("meat")
    # 食物组
    group = "other"
    for g, kws in FGROUP_RULES:
        if any(k in name for k in kws):
            group = g
            break
    # 营养
    if name in CURATED:
        kcal, p, f, c = CURATED[name]
    else:
        kcal, p, f, c = FOOD_GROUPS[group]
    return group, tags, {"kcal": kcal, "protein": p, "fat": f, "carbs": c}


def main():
    _alter()
    db = SessionLocal()
    try:
        ings = db.query(Ingredient).all()
        done = 0
        for ing in ings:
            name = (ing.name or "").strip()
            if not name:
                continue
            group, tags, nut = classify_and_score(name)
            ing.food_group = group
            ing.diet_tags = tags
            ing.nutrition = nut
            done += 1
        db.commit()
        print(f"完成：食材 {done}/{len(ings)} 个已分类回填")
    finally:
        db.close()


if __name__ == "__main__":
    main()